#!/usr/bin/env python3
"""Generate the 8x13 grayscale spinner and the core 0.51.0 boot payload."""
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parent
POINTS = ((6, 0), (8, 1), (9, 3), (8, 5), (6, 6), (4, 5), (3, 3), (4, 1))
frames = []
for head in range(len(POINTS)):
    pixels = bytearray(104)
    for offset in (0, len(POINTS) // 2):
        x, y = POINTS[(head + offset) % len(POINTS)]
        pixels[y * 13 + x] = 192
    frames.append(bytes(pixels))
header = '// Generated by ../generate-spinner.py; do not edit.\n'
header += '#include <stdint.h>\nstatic const uint8_t kSpinnerFrames[8][104] = {\n'
header += ''.join('  {' + ','.join(map(str, frame)) + '},\n' for frame in frames)
header += '};\n'
(ROOT / 'spinner/spinner_frames.h').write_text(header)
# The stock matrix player holds each grayscale frame for 16 ms. Eight repeats
# per position match the sketch's 128 ms cadence (1.024 seconds per revolution).
loop = b''.join(frame * 8 for frame in frames)
end = bytes(104)
output = ROOT / 'build'
output.mkdir(exist_ok=True)
(output / 'boot-spinner.bin').write_bytes(struct.pack('<4I', 0xBA, len(loop), len(end), 0) + loop + end)
